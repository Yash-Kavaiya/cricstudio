import puppeteer from 'puppeteer-core';
const base='https://cricstudio.vercel.app';
const b = await puppeteer.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:'new',args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--autoplay-policy=no-user-gesture-required']});
const p = await b.newPage(); await p.setViewport({width:1440,height:900});
const issues=[];
p.on('console',m=>{ if(['error','warning'].includes(m.type())) issues.push(`[console.${m.type()}] ${m.text().slice(0,220)}`)});
p.on('pageerror',e=>issues.push(`[pageerror] ${e.message.slice(0,220)}`));
p.on('requestfailed',r=>issues.push(`[requestfailed] ${r.url().slice(0,120)} ${r.failure()?.errorText}`));
p.on('response',r=>{ if(r.status()>=400) issues.push(`[http ${r.status()}] ${r.url().slice(0,140)}`)});
const step=async(n,f)=>{issues.push(`--- ${n}`); await f(); await new Promise(x=>setTimeout(x,2500));};
await step('dashboard', ()=>p.goto(base+'/',{waitUntil:'networkidle2'}));
const r = await fetch(base+'/api/studios',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({name:'Prod check',matchKey:'demo:replay'})}).then(r=>r.json());
await p.evaluate((s)=>localStorage.setItem('cricstudio.studios',JSON.stringify([{...s,matchKey:'demo:replay',createdAt:Date.now()}])),r);
await step('green room', ()=>p.goto(base+'/studio/'+r.id,{waitUntil:'networkidle2'}));
const click=async(t)=>p.evaluate((t)=>{const el=[...document.querySelectorAll('button,[role=tab]')].find(e=>e.textContent.trim().includes(t)); el?.click(); return !!el;},t);
await step('enter studio', ()=>click('Enter studio')); await new Promise(x=>setTimeout(x,3000));
for (const t of ['Auto','Director','Audio','Stream','Brand','Chat','Match']) await step('tab '+t, ()=>click(t));
await step('scene ball by ball', ()=>click('Ball by Ball'));
await step('scene live score', ()=>click('Live Score'));
await step('settings dialog', ()=>p.evaluate(()=>{ const btn=[...document.querySelectorAll('button')].find(e=>e.getAttribute('aria-label')==='Audio & video settings'||e.textContent.includes('settings')); btn?.click(); }));
await step('join page', ()=>p.goto(base+'/join/'+r.guestToken,{waitUntil:'networkidle2'}));
await step('program page', ()=>p.goto(`${base}/program/${r.id}?k=${encodeURIComponent(r.programToken)}`,{waitUntil:'networkidle2'}));
console.log(issues.join('\n')); console.log('ID',r.id);
await b.close();
