// Generates rust/app/src/catalog.rs from the shared TypeScript catalogs, so ids can never drift.
// Run from the repo root: npx tsx rust/golden/gen-catalog.ts
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { BACKGROUNDS, EDGE_LANG_VOICES, FONT_PAIRS, GNANI_VOICES, PLATFORM_PRESETS, SCENES, STT_LANGUAGES, TRANSITIONS, VOICES } from '../../packages/shared/src/index';

const q = (s: string) => JSON.stringify(s);
const list = (name: string, ids: string[]) => `pub const ${name}: [&str; ${ids.length}] = [${ids.map(q).join(', ')}];\n`;
const scenes = SCENES.map((s) => `    Scene { id: ${q(s.id)}, group: ${q(s.group)}, uses_cameras: ${s.usesCameras}, autopilot: ${s.autopilot} },`).join('\n');
const edge = Object.entries(EDGE_LANG_VOICES).map(([l, v]) => `(${q(l)}, ${q(v)})`).join(', ');
const presets = Object.entries(PLATFORM_PRESETS).map(([id, p]) => `(${q(id)}, ${q(p.label)}, ${q(p.url)})`).join(', ');

const out = `// @generated by rust/golden/gen-catalog.ts from packages/shared. Do not edit.

#[derive(Clone, Copy, Debug)]
pub struct Scene {
    pub id: &'static str,
    pub group: &'static str,
    pub uses_cameras: bool,
    pub autopilot: bool,
}

pub const SCENES: [Scene; ${SCENES.length}] = [
${scenes}
];

${list('BACKGROUNDS', BACKGROUNDS.map((b) => b.id))}${list('FONT_PAIRS', FONT_PAIRS.map((f) => f.id))}${list('TRANSITIONS', TRANSITIONS.map((t) => t.id))}${list('VOICES', VOICES.map((v) => v.id))}${list('GNANI_VOICES', GNANI_VOICES.map((v) => v.id))}${list('STT_LANGUAGES', STT_LANGUAGES.map((l) => l.code))}
pub const EDGE_LANG_VOICES: [(&str, &str); ${Object.keys(EDGE_LANG_VOICES).length}] = [${edge}];

/// (platform, label, default RTMP url)
pub const PLATFORMS: [(&str, &str, &str); ${Object.keys(PLATFORM_PRESETS).length}] = [${presets}];

pub fn scene(id: &str) -> Option<&'static Scene> {
    SCENES.iter().find(|s| s.id == id)
}

pub fn edge_voice(lang: &str) -> Option<&'static str> {
    EDGE_LANG_VOICES.iter().find(|(l, _)| *l == lang).map(|(_, v)| *v)
}
`;
writeFileSync(resolve(import.meta.dirname, '..', 'app', 'src', 'catalog.rs'), out);
console.log(`catalog: ${SCENES.length} scenes, ${BACKGROUNDS.length} backgrounds, ${TRANSITIONS.length} transitions`);
